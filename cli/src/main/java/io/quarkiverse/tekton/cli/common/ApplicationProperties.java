package io.quarkiverse.tekton.cli.common;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.stream.Collectors;

import io.quarkiverse.tekton.task.ParamDefinition;
import io.quarkiverse.tekton.task.StepDefinition;
import io.quarkiverse.tekton.task.TaskDefinition;
import io.quarkiverse.tekton.task.WorkspaceDefinition;

/**
 * Writes the {@code quarkus.tekton.task.<name>.*} properties of a custom task to the application.properties of a
 * project. The file is edited as text (and not using {@link java.util.Properties#store}) to keep its comments and the
 * order of its properties.
 */
public class ApplicationProperties {

    private static final String TASK_PREFIX = "quarkus.tekton.task.";

    public static Path path(Path projectRoot) {
        return projectRoot.resolve("src").resolve("main").resolve("resources").resolve("application.properties");
    }

    public static String comment(String taskName) {
        return "# Task " + taskName + " generated by: quarkus tekton task generate";
    }

    /**
     * The properties declaring the task, as read by SmallRye Config: list items are separated by {@code ,} and the
     * expressions ({@code ${...}}) are escaped.
     */
    public static Map<String, String> taskProperties(TaskDefinition def) {
        Map<String, String> properties = new LinkedHashMap<>();
        String prefix = TASK_PREFIX + segment(def.name()) + ".";
        StepDefinition step = def.steps().get(0);

        def.description().ifPresent(v -> properties.put(prefix + "description", value(v)));
        properties.put(prefix + "image", value(step.image()));
        step.script().ifPresent(v -> properties.put(prefix + "script", value(v)));
        if (!step.command().isEmpty()) {
            properties.put(prefix + "command", list(step.command()));
        }
        if (!step.args().isEmpty()) {
            properties.put(prefix + "args", list(step.args()));
        }
        step.env().forEach((name, v) -> properties.put(prefix + "env." + segment(name), value(v)));

        for (ParamDefinition param : def.params()) {
            String paramPrefix = prefix + "param." + segment(param.name()) + ".";
            if (!"string".equals(param.type())) {
                properties.put(paramPrefix + "type", value(param.type()));
            }
            param.defaultValue().ifPresent(v -> properties.put(paramPrefix + "default", value(v)));
            param.description().ifPresent(v -> properties.put(paramPrefix + "description", value(v)));
            if (!param.properties().isEmpty()) {
                properties.put(paramPrefix + "properties", list(param.properties()));
            }
        }

        for (WorkspaceDefinition workspace : def.workspaces()) {
            String workspacePrefix = prefix + "workspace." + segment(workspace.name()) + ".";
            workspace.mountPath().ifPresent(v -> properties.put(workspacePrefix + "mount-path", value(v)));
            if (workspace.optional()) {
                properties.put(workspacePrefix + "optional", "true");
            }
            workspace.description().ifPresent(v -> properties.put(workspacePrefix + "description", value(v)));
        }

        step.workingDir().ifPresent(v -> properties.put(prefix + "working-dir", value(v)));
        return properties;
    }

    /**
     * The lines of the application.properties declaring the task: a comment followed by its properties, escaped for
     * the {@code .properties} format.
     */
    public static List<String> taskLines(TaskDefinition def) {
        List<String> lines = new ArrayList<>();
        lines.add(comment(def.name()));
        taskProperties(def).forEach((key, value) -> {
            // a multi-line value is written using continuation lines
            lines.addAll(List.of((escapeKey(key) + "=" + escapeValue(value)).split("\n", -1)));
        });
        return lines;
    }

    /**
     * Writes the lines of the task to the given file, created if it doesn't exist.
     * The properties (and comment) already declaring the task are replaced by the given lines.
     *
     * @return true if the task was already declared in the file, false otherwise
     */
    public static boolean writeTask(Path file, String taskName, List<String> taskLines) {
        try {
            String content = Files.exists(file) ? Files.readString(file, StandardCharsets.UTF_8) : "";
            String separator = content.contains("\r\n") ? "\r\n" : "\n";
            List<String> lines = content.lines().toList();

            String comment = comment(taskName);
            List<String> result = new ArrayList<>();
            int insertAt = -1;
            for (int i = 0; i < lines.size(); i++) {
                String line = lines.get(i);
                String trimmed = line.stripLeading();
                if (trimmed.equals(comment)) {
                    insertAt = insertAt < 0 ? result.size() : insertAt;
                    continue;
                }
                boolean taskProperty = isTaskProperty(trimmed, taskName);
                if (taskProperty) {
                    insertAt = insertAt < 0 ? result.size() : insertAt;
                } else {
                    result.add(line);
                }
                if (isComment(trimmed)) {
                    continue;
                }
                // continuation lines belong to the same property
                String current = line;
                while (continues(current) && i + 1 < lines.size()) {
                    current = lines.get(++i);
                    if (!taskProperty) {
                        result.add(current);
                    }
                }
            }

            if (insertAt >= 0) {
                result.addAll(insertAt, taskLines);
            } else {
                if (!result.isEmpty() && !result.get(result.size() - 1).isBlank()) {
                    result.add("");
                }
                result.addAll(taskLines);
            }

            if (file.getParent() != null && !Files.exists(file.getParent())) {
                Files.createDirectories(file.getParent());
            }
            Files.writeString(file, String.join(separator, result) + separator, StandardCharsets.UTF_8);
            return insertAt >= 0;
        } catch (IOException e) {
            throw new RuntimeException(e);
        }
    }

    private static boolean isTaskProperty(String line, String taskName) {
        return line.startsWith(TASK_PREFIX + taskName + ".") || line.startsWith(TASK_PREFIX + "\"" + taskName + "\".");
    }

    private static boolean isComment(String line) {
        return line.startsWith("#") || line.startsWith("!");
    }

    /**
     * A line ending with an odd number of backslashes continues on the next line.
     */
    private static boolean continues(String line) {
        int backslashes = 0;
        for (int i = line.length() - 1; i >= 0 && line.charAt(i) == '\\'; i--) {
            backslashes++;
        }
        return backslashes % 2 == 1;
    }

    /**
     * A segment of a property name containing dots (e.g. the name of a task) is quoted.
     */
    static String segment(String name) {
        return name.contains(".") ? "\"" + name + "\"" : name;
    }

    /**
     * Escapes the expressions of a value: SmallRye Config expands {@code ${...}} and replaces {@code $$} by {@code $}.
     */
    static String value(String value) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < value.length(); i++) {
            char c = value.charAt(i);
            sb.append(c);
            if (c == '$' && i + 1 < value.length() && (value.charAt(i + 1) == '{' || value.charAt(i + 1) == '$')) {
                sb.append('$');
            }
        }
        return sb.toString();
    }

    /**
     * Joins the items of a list, escaping the {@code ,} (separator) and {@code \} (escape) of SmallRye Config.
     */
    static String list(List<String> items) {
        return value(items.stream()
                .map(item -> item.replace("\\", "\\\\").replace(",", "\\,"))
                .collect(Collectors.joining(",")));
    }

    static String escapeKey(String key) {
        StringBuilder sb = new StringBuilder();
        for (char c : key.toCharArray()) {
            switch (c) {
                case '\\', ' ', ':', '=', '#', '!' -> sb.append('\\').append(c);
                case '\t' -> sb.append("\\t");
                case '\n' -> sb.append("\\n");
                case '\r' -> sb.append("\\r");
                case '\f' -> sb.append("\\f");
                default -> sb.append(c);
            }
        }
        return sb.toString();
    }

    /**
     * Escapes a value for the {@code .properties} format. The line breaks are written as {@code \n} followed by a
     * continuation line, whose leading space is escaped as it would be dropped otherwise.
     */
    static String escapeValue(String value) {
        StringBuilder sb = new StringBuilder();
        boolean lineStart = true;
        for (int i = 0; i < value.length(); i++) {
            char c = value.charAt(i);
            switch (c) {
                case '\\' -> sb.append("\\\\");
                case '\n' -> {
                    sb.append("\\n");
                    if (i + 1 < value.length()) {
                        sb.append("\\\n");
                        lineStart = true;
                        continue;
                    }
                }
                case '\r' -> sb.append("\\r");
                case '\t' -> sb.append("\\t");
                case '\f' -> sb.append("\\f");
                case ' ' -> sb.append(lineStart ? "\\ " : " ");
                default -> sb.append(c);
            }
            lineStart = false;
        }
        return sb.toString();
    }
}
