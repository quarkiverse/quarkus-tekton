package io.quarkiverse.tekton.cli.common;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.IOException;
import java.io.StringReader;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.Properties;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import io.quarkiverse.tekton.task.ParamDefinition;
import io.quarkiverse.tekton.task.StepDefinition;
import io.quarkiverse.tekton.task.TaskDefinition;
import io.quarkiverse.tekton.task.WorkspaceDefinition;
import io.smallrye.config.PropertiesConfigSource;
import io.smallrye.config.SmallRyeConfig;
import io.smallrye.config.SmallRyeConfigBuilder;

class ApplicationPropertiesTest {

    @TempDir
    Path dir;

    private static TaskDefinition hello() {
        StepDefinition step = new StepDefinition(null, "registry.access.redhat.com/ubi9/ubi-minimal",
                Optional.of("echo \"Hello $(params.who)\""), List.of(), List.of(),
                Optional.of("$(workspaces.project-dir.path)"), Map.of("GREETING_ENV", "tekton"));
        return new TaskDefinition("hello", Optional.empty(),
                List.of(new ParamDefinition("labels", "object", Optional.empty(), Optional.empty(), List.of("app", "tier")),
                        new ParamDefinition("who", null, Optional.of("world"), Optional.of("Who to greet"))),
                List.of(new WorkspaceDefinition("project-dir", Optional.empty(), true, Optional.empty())),
                List.of(step));
    }

    @Test
    void createsTheFile() throws IOException {
        Path file = ApplicationProperties.path(dir);

        assertFalse(ApplicationProperties.writeTask(file, "hello", ApplicationProperties.taskLines(hello())));

        assertEquals("""
                # Task hello generated by: quarkus tekton task generate
                quarkus.tekton.task.hello.image=registry.access.redhat.com/ubi9/ubi-minimal
                quarkus.tekton.task.hello.script=echo "Hello $(params.who)"
                quarkus.tekton.task.hello.env.GREETING_ENV=tekton
                quarkus.tekton.task.hello.param.labels.type=object
                quarkus.tekton.task.hello.param.labels.properties=app,tier
                quarkus.tekton.task.hello.param.who.default=world
                quarkus.tekton.task.hello.param.who.description=Who to greet
                quarkus.tekton.task.hello.workspace.project-dir.optional=true
                quarkus.tekton.task.hello.working-dir=$(workspaces.project-dir.path)
                """, Files.readString(file));
    }

    @Test
    void appendsTheTaskKeepingTheOtherLines() throws IOException {
        Path file = ApplicationProperties.path(dir);
        Files.createDirectories(file.getParent());
        Files.writeString(file, """
                # My application
                quarkus.application.name=demo
                quarkus.tekton.task.hello-world.image=ubi
                """);

        assertFalse(
                ApplicationProperties.writeTask(file, "hello", List.of("# Task hello", "quarkus.tekton.task.hello.image=new")));

        assertEquals("""
                # My application
                quarkus.application.name=demo
                quarkus.tekton.task.hello-world.image=ubi

                # Task hello
                quarkus.tekton.task.hello.image=new
                """, Files.readString(file));
    }

    @Test
    void replacesTheExistingTask() throws IOException {
        Path file = ApplicationProperties.path(dir);
        Files.createDirectories(file.getParent());
        Files.writeString(file, """
                # My application
                quarkus.application.name=demo

                # Task hello generated by: quarkus tekton task generate
                quarkus.tekton.task.hello.image=old
                quarkus.tekton.task."hello".script=echo a\\n\\
                quarkus.tekton.task.other.image=continuation of the script
                # keep this comment
                quarkus.tekton.task.hello-world.image=ubi \\
                  quarkus.tekton.task.hello.image=continuation of another property
                   quarkus.tekton.task.hello.param.who.default=world
                """);

        assertTrue(ApplicationProperties.writeTask(file, "hello",
                List.of(ApplicationProperties.comment("hello"), "quarkus.tekton.task.hello.image=new")));

        assertEquals("""
                # My application
                quarkus.application.name=demo

                # Task hello generated by: quarkus tekton task generate
                quarkus.tekton.task.hello.image=new
                # keep this comment
                quarkus.tekton.task.hello-world.image=ubi \\
                  quarkus.tekton.task.hello.image=continuation of another property
                """, Files.readString(file));
    }

    @Test
    void quotesTheNamesContainingDots() {
        StepDefinition step = new StepDefinition(null, "ubi", Optional.of("env"), List.of(), List.of(), Optional.empty(),
                Map.of("MY.VAR", "1"));
        TaskDefinition def = new TaskDefinition("my.task", Optional.empty(),
                List.of(new ParamDefinition("a.b", null, Optional.empty(), Optional.of("dotted"))), List.of(),
                List.of(step));

        assertEquals(List.of(
                "quarkus.tekton.task.\"my.task\".image",
                "quarkus.tekton.task.\"my.task\".script",
                "quarkus.tekton.task.\"my.task\".env.\"MY.VAR\"",
                "quarkus.tekton.task.\"my.task\".param.\"a.b\".description"),
                List.copyOf(ApplicationProperties.taskProperties(def).keySet()));
    }

    @Test
    void escapesTheValues() throws IOException {
        String script = """
                #!/bin/sh
                if [ -n "${HOME}" ]; then
                  echo "pid $$ in C:\\temp"
                \techo tab
                fi
                """;
        StepDefinition step = new StepDefinition(null, "ubi", Optional.of(script), List.of(), List.of("a,b", "c\\d", " e"),
                Optional.empty(), Map.of("GREETING", " hello ${USER}"));
        TaskDefinition def = new TaskDefinition("hello", Optional.of("Say: hello = world"), List.of(), List.of(),
                List.of(step));

        List<String> lines = ApplicationProperties.taskLines(def);
        assertTrue(lines.contains("quarkus.tekton.task.hello.script=#!/bin/sh\\n\\"), String.join("\n", lines));
        assertTrue(lines.contains("\\  echo \"pid $$$ in C:\\\\temp\"\\n\\"), String.join("\n", lines));

        // read the lines as the CLI (java.util.Properties) and SmallRye Config do
        Properties properties = new Properties();
        properties.load(new StringReader(String.join("\n", lines)));
        Map<String, String> values = new HashMap<>();
        properties.stringPropertyNames().forEach(name -> values.put(name, properties.getProperty(name)));
        SmallRyeConfig config = new SmallRyeConfigBuilder()
                .addDefaultInterceptors()
                .withSources(new PropertiesConfigSource(values, "test", 250))
                .build();

        assertEquals(script, config.getValue("quarkus.tekton.task.hello.script", String.class));
        assertEquals(List.of("a,b", "c\\d", " e"), config.getValues("quarkus.tekton.task.hello.args", String.class));
        assertEquals(" hello ${USER}", config.getValue("quarkus.tekton.task.hello.env.GREETING", String.class));
        assertEquals("Say: hello = world", config.getValue("quarkus.tekton.task.hello.description", String.class));
    }
}
